"""Prepare and export a matched Lumiac USB/SD and OTA release without flashing."""
from pathlib import Path
import hashlib
import json
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
MARLIN = ROOT / 'Marlin/marlin-2.1.2.6'
ESP = ROOT / 'ESP_RF_Octopus'
OUTPUT = ROOT / 'firmware'

def prepare():
    release = json.loads((ROOT / 'shared/release.json').read_text())
    contract = b'Lumiac cloud protocol 1\n' + b''.join(
        (MARLIN / 'Marlin' / name).read_bytes().replace(b'\r\n', b'\n')
        for name in ('Configuration.h', 'Configuration_adv.h'))
    identity = 'LUMIAC1-' + hashlib.sha256(contract).hexdigest()[:12]
    revision = release['revision']
    branch = release.get('branch', 'RF')
    if branch not in ('RF', 'onetoone'):
        raise ValueError('Unknown firmware source branch')
    header = ('// Generated by tools/firmware_package.py\n#pragma once\n'
              f'#define LUMIAC_FIRMWARE_ID "{identity}"\n'
              f'#define LUMIAC_FIRMWARE_REVISION "{revision}"\n'
              f'#define LUMIAC_FIRMWARE_BRANCH "{branch}"\n')
    for path in (ESP / 'src/build_version.h', MARLIN / 'Marlin/lumiac_build.h'):
        if not path.exists() or path.read_text() != header:
            path.write_text(header, encoding='utf-8', newline='\n')
    protocol = (ROOT / 'shared/firmware_transfer.h').read_bytes()
    protocol_path = MARLIN / 'Marlin/src/feature/lumiac_update_protocol.h'
    if not protocol_path.exists() or protocol_path.read_bytes() != protocol:
        protocol_path.write_bytes(protocol)
    # SDK defaults do not override an existing local sdkconfig. Migrate it too.
    sdk = ESP / 'sdkconfig.esp32dev'
    if sdk.exists():
        values = {'CONFIG_PARTITION_TABLE_SINGLE_APP': None,
                  'CONFIG_PARTITION_TABLE_SINGLE_APP_LARGE': None,
                  'CONFIG_PARTITION_TABLE_TWO_OTA': None,
                  'CONFIG_PARTITION_TABLE_CUSTOM': 'y',
                  'CONFIG_PARTITION_TABLE_CUSTOM_FILENAME': '"partitions_ota.csv"',
                  'CONFIG_PARTITION_TABLE_FILENAME': '"partitions_ota.csv"',
                  'CONFIG_MBEDTLS_PSK_MODES': 'y',
                  'CONFIG_MBEDTLS_KEY_EXCHANGE_PSK': 'y'}
        lines = [line for line in sdk.read_text().splitlines()
                 if not any(line.startswith(key + '=') or line == '# ' + key + ' is not set' for key in values)]
        lines += [f'{key}={value}' if value is not None else '# ' + key + ' is not set' for key, value in values.items()]
        content = '\n'.join(lines) + '\n'
        if sdk.read_text() != content:
            sdk.write_text(content)
    return identity, revision

def export():
    identity, revision = prepare()
    OUTPUT.mkdir(exist_ok=True)
    images = {'esp12.bin': ESP / '.pio/build/esp12s/firmware.bin',
              'esp32.bin': ESP / '.pio/build/esp32dev/firmware.bin',
              'octopus.bin': MARLIN / '.pio/build/STM32F446ZE_btt/firmware.bin'}
    limits = {'esp12.bin': 0x100000, 'esp32.bin': 0x1c0000, 'octopus.bin': 0x60000}
    manifest = {'identity': identity, 'revision': revision,
                'branch': json.loads((ROOT / 'shared/release.json').read_text()).get('branch', 'RF'), 'images': {}}
    for name, path in images.items():
        data = path.read_bytes()
        role = name.removesuffix('.bin')
        if not 1024 <= len(data) <= limits[name] or identity.encode() not in data or revision.encode() not in data or ('LUMIAC_OTA_ROLE:' + role).encode() not in data:
            raise ValueError(f'Rebuild the matching {role} image before exporting')
        if role in ('esp12', 'esp32') and b'LUMIAC_LOCAL_OTA_V1' not in data:
            raise ValueError(f'Rebuild {role} with hotspot update recovery before exporting')
        shutil.copy2(path, OUTPUT / name)
        manifest['images'][name] = {'size': len(data), 'sha256': hashlib.sha256(data).hexdigest()}
    build = ESP / '.pio/build/esp32dev'
    for name in ('bootloader.bin', 'partitions.bin'):
        target = 'esp32_' + name
        shutil.copy2(build / name, OUTPUT / target)
        data = (OUTPUT / target).read_bytes()
        manifest['images'][target] = {'size': len(data), 'sha256': hashlib.sha256(data).hexdigest()}
    boot_app = build / 'ota_data_initial.bin'
    target = 'esp32_boot_app0.bin'
    shutil.copy2(boot_app, OUTPUT / target)
    data = (OUTPUT / target).read_bytes()
    manifest['images'][target] = {'size': len(data), 'sha256': hashlib.sha256(data).hexdigest()}
    (OUTPUT / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(f'Exported {identity}, revision {revision}: {OUTPUT}')

def verify():
    manifest = json.loads((OUTPUT / 'manifest.json').read_text())
    for name, info in manifest['images'].items():
        data = (OUTPUT / name).read_bytes()
        if len(data) != info['size'] or hashlib.sha256(data).hexdigest() != info['sha256']:
            raise ValueError(f'Firmware checksum failed: {name}')
    print(f"Verified {manifest['identity']}, revision {manifest['revision']}")
    return manifest

if __name__ == '__main__':
    action = sys.argv[1] if len(sys.argv) > 1 else 'all'
    if action == 'all':
        prepare()
        for target in ('marlin', 'esp12', 'esp32'):
            subprocess.run([sys.executable, str(ROOT / 'build.py'), target, '--build-only'], check=True)
        export()
    elif action == 'prepare': print(prepare())
    elif action == 'export': export()
    elif action == 'verify': verify()
    else: raise SystemExit('Use all, prepare, export, or verify')
